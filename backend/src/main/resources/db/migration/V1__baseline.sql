-- V1: baseline do schema do Portal do Instrutor.
-- Reproduz o schema atual das entidades JPA, com FKs ON DELETE CASCADE,
-- constraints únicas nomeadas e índices úteis.
-- Para bancos já existentes, configure spring.flyway.baseline-on-migrate=true
-- (a migração é marcada como aplicada sem reexecutar).

CREATE TABLE usuarios (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        varchar(120) NOT NULL,
    login       varchar(50)  NOT NULL,
    email       varchar(120) NOT NULL,
    cpf         varchar(11)  NOT NULL,
    senha_hash  varchar(255) NOT NULL,
    ativo       boolean      NOT NULL DEFAULT true,
    CONSTRAINT uk_usuario_login UNIQUE (login),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT uk_usuario_cpf   UNIQUE (cpf)
);

CREATE TABLE turmas (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             varchar(100) NOT NULL,
    codigo           varchar(30),
    curso            varchar(100),
    turno            varchar(20),
    sala             varchar(30),
    qtd_alunos       integer,
    qtd_ucs          integer,
    horas            integer,
    ativa            boolean      NOT NULL DEFAULT true,
    instrutor_login  varchar(50)  NOT NULL,
    CONSTRAINT uk_turma_codigo_instrutor UNIQUE (codigo, instrutor_login),
    CONSTRAINT fk_turma_instrutor FOREIGN KEY (instrutor_login) REFERENCES usuarios (login) ON DELETE CASCADE
);

CREATE TABLE alunos (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       varchar(120) NOT NULL,
    matricula  varchar(30)  NOT NULL,
    cpf        varchar(11),
    ativo      boolean      NOT NULL DEFAULT true,
    turma_id   bigint       NOT NULL,
    CONSTRAINT uk_aluno_turma_matricula UNIQUE (turma_id, matricula),
    CONSTRAINT uk_aluno_turma_cpf       UNIQUE (turma_id, cpf),
    CONSTRAINT fk_aluno_turma FOREIGN KEY (turma_id) REFERENCES turmas (id) ON DELETE CASCADE
);

CREATE TABLE aulas (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo     varchar(100)     NOT NULL,
    data_hora  timestamptz      NOT NULL,
    sala       varchar(30),
    turma_id   bigint           NOT NULL,
    CONSTRAINT fk_aula_turma FOREIGN KEY (turma_id) REFERENCES turmas (id) ON DELETE CASCADE
);

CREATE TABLE avaliacoes (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo    varchar(100) NOT NULL,
    data      date         NOT NULL,
    turma_id  bigint       NOT NULL,
    CONSTRAINT fk_avaliacao_turma FOREIGN KEY (turma_id) REFERENCES turmas (id) ON DELETE CASCADE
);

CREATE TABLE notas (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avaliacao_id  bigint       NOT NULL,
    aluno_id      bigint       NOT NULL,
    valor         numeric(4,1),
    CONSTRAINT uk_nota_avaliacao_aluno UNIQUE (avaliacao_id, aluno_id),
    CONSTRAINT fk_nota_avaliacao FOREIGN KEY (avaliacao_id) REFERENCES avaliacoes (id) ON DELETE CASCADE,
    CONSTRAINT fk_nota_aluno     FOREIGN KEY (aluno_id)     REFERENCES alunos (id)     ON DELETE CASCADE
);

CREATE TABLE frequencias (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id   bigint  NOT NULL,
    turma_id   bigint  NOT NULL,
    data       date    NOT NULL,
    presente   boolean NOT NULL,
    CONSTRAINT uk_frequencia_aluno_data UNIQUE (aluno_id, data),
    CONSTRAINT fk_frequencia_aluno FOREIGN KEY (aluno_id) REFERENCES alunos (id) ON DELETE CASCADE,
    CONSTRAINT fk_frequencia_turma FOREIGN KEY (turma_id) REFERENCES turmas (id) ON DELETE CASCADE
);

CREATE TABLE ocorrencias (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id         bigint        NOT NULL,
    turma_id         bigint        NOT NULL,
    instrutor_login  varchar(50)   NOT NULL,
    data             date          NOT NULL,
    descricao        varchar(2000) NOT NULL,
    criado_em        timestamp     NOT NULL,
    CONSTRAINT fk_ocorrencia_aluno     FOREIGN KEY (aluno_id)        REFERENCES alunos (id)        ON DELETE CASCADE,
    CONSTRAINT fk_ocorrencia_turma     FOREIGN KEY (turma_id)        REFERENCES turmas (id)        ON DELETE CASCADE,
    CONSTRAINT fk_ocorrencia_instrutor FOREIGN KEY (instrutor_login) REFERENCES usuarios (login)   ON DELETE CASCADE
);

CREATE TABLE eventos (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrutor_login  varchar(50)  NOT NULL,
    titulo           varchar(100) NOT NULL,
    tipo             varchar(20)  NOT NULL,
    data             date         NOT NULL,
    hora             time,
    turma_nome       varchar(60),
    descricao        varchar(500),
    turma_id         bigint,
    CONSTRAINT fk_evento_instrutor FOREIGN KEY (instrutor_login) REFERENCES usuarios (login) ON DELETE CASCADE,
    CONSTRAINT fk_evento_turma     FOREIGN KEY (turma_id)        REFERENCES turmas (id)       ON DELETE SET NULL
);

CREATE TABLE atividades (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrutor_login  varchar(50)  NOT NULL,
    descricao        varchar(500) NOT NULL,
    criado_em        timestamp    NOT NULL,
    CONSTRAINT fk_atividade_instrutor FOREIGN KEY (instrutor_login) REFERENCES usuarios (login) ON DELETE CASCADE
);

CREATE TABLE unidades_curriculares (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           varchar(100) NOT NULL,
    carga_horaria  integer      NOT NULL,
    turma_id       bigint       NOT NULL,
    CONSTRAINT fk_uc_turma FOREIGN KEY (turma_id) REFERENCES turmas (id) ON DELETE CASCADE
);

CREATE INDEX idx_frequencia_turma_data ON frequencias (turma_id, data);
CREATE INDEX idx_nota_avaliacao ON notas (avaliacao_id);
CREATE INDEX idx_aluno_turma_ativo ON alunos (turma_id, ativo);
CREATE INDEX idx_evento_instrutor_data ON eventos (instrutor_login, data);
CREATE INDEX idx_atividade_instrutor_criado ON atividades (instrutor_login, criado_em DESC);
CREATE INDEX idx_aula_turma_data_hora ON aulas (turma_id, data_hora);
